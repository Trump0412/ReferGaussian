      export GS_QUERY_CLOUD_FILL_CONVEX_HULL="${GS_QUERY_CLOUD_FILL_CONVEX_HULL:-1}"
      export GS_QUERY_CLOUD_HULL_MAX_AREA_MULTIPLIER="${GS_QUERY_CLOUD_HULL_MAX_AREA_MULTIPLIER:-6}"

