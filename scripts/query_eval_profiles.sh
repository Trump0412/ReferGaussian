      export QUERY_LIFT_MAX_GAUSSIANS="${QUERY_LIFT_MAX_GAUSSIANS:-3072}"
      export QUERY_LIFT_BOUNDARY_MAX_ITER="${QUERY_LIFT_BOUNDARY_MAX_ITER:-10}"
      export QUERY_LIFT_BOUNDARY_BATCH_FRAMES="${QUERY_LIFT_BOUNDARY_BATCH_FRAMES:-12}"
      export QUERY_LIFT_BOUNDARY_SEEDS="${QUERY_LIFT_BOUNDARY_SEEDS:-12}"
      export QUERY_LIFT_BOUNDARY_TARGET_IOU="${QUERY_LIFT_BOUNDARY_TARGET_IOU:-0.90}"
      export QUERY_LIFT_BOUNDARY_TARGET_AREA_RATIO="${QUERY_LIFT_BOUNDARY_TARGET_AREA_RATIO:-1.00}"
