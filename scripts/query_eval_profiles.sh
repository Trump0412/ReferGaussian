      export GS_QUERY_FUSE_PREFER_CLIPPED_CLOUD="${GS_QUERY_FUSE_PREFER_CLIPPED_CLOUD:-0}"
      export GS_QUERY_ALLOW_CLOUD_ONLY_WITH_QUERY="${GS_QUERY_ALLOW_CLOUD_ONLY_WITH_QUERY:-1}"
      export GS_QUERY_CLOUD_BOX_EXPANSION="${GS_QUERY_CLOUD_BOX_EXPANSION:-0}"
      export GS_QUERY_CLOUD_NO_STAGE1_RADIUS_MULT="${GS_QUERY_CLOUD_NO_STAGE1_RADIUS_MULT:-1.0}"
