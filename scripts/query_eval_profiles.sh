      export GS_QUERY_FUSE_PREV_IOU_WEIGHT="${GS_QUERY_FUSE_PREV_IOU_WEIGHT:-0.18}"
      export GS_QUERY_FUSE_QUERY_WEIGHT="${GS_QUERY_FUSE_QUERY_WEIGHT:-0.58}"
      export GS_QUERY_FUSE_CLOUD_WEIGHT="${GS_QUERY_FUSE_CLOUD_WEIGHT:-0.18}"
      export GS_QUERY_EXPORT_ENTITY_LIFECYCLE="${GS_QUERY_EXPORT_ENTITY_LIFECYCLE:-1}"
      ;;
    boundary_shape_v2|mask_shape_refine_v2)
      export QUERY_EVAL_PROFILE="boundary_shape_v2"
      export REFERGAUSSIAN_QUERY_EVAL_PROFILE="boundary_shape_v2"

      # Use v1's proven boundary_refine lifting with expanded Gaussian budget.
