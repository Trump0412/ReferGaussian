      export GS_QUERY_FUSE_RECOVERY_KERNEL="${GS_QUERY_FUSE_RECOVERY_KERNEL:-35}"
      export GS_QUERY_FUSE_RECOVERY_MIN_CLIP_AREA_RATIO="${GS_QUERY_FUSE_RECOVERY_MIN_CLIP_AREA_RATIO:-0.45}"
      export GS_QUERY_FUSE_RECOVERY_MIN_QUERY_RECALL="${GS_QUERY_FUSE_RECOVERY_MIN_QUERY_RECALL:-0.22}"
      export GS_QUERY_FUSE_ALLOW_QUERY_SUPPORTED_BY_CLOUD="${GS_QUERY_FUSE_ALLOW_QUERY_SUPPORTED_BY_CLOUD:-0}"
